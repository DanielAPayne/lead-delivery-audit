// Build docs/index.html: one self-contained page (engine + examples inlined),
// so it works from GitHub Pages or saved to disk and opened offline.
//   node scripts/build-web.js          write docs/index.html
//   node scripts/build-web.js --check  exit 1 if docs/index.html is stale

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const MODULES = ['csv.js', 'receipts.js', 'engine.js', 'report.js']; // dependency order
const OUT = join(root, 'docs', 'index.html');

export function inlineModule(source, name) {
  const body = source
    .replace(/^import\s[^;]*;\s*$/gm, '')
    .replace(/^export\s+(?=(const|function|class|let|async)\b)/gm, '');
  if (/^\s*(import|export)\b/m.test(body)) throw new Error(`${name}: unsupported import/export form`);
  return `// ---- src/${name} ----\n${body.trim()}\n`;
}

const scriptSafe = s => s.replace(/<\/(script)/gi, '<\\/$1').replace(/<!--/g, '<\\!--');

export function build() {
  const engine = MODULES.map(m => inlineModule(readFileSync(join(root, 'src', m), 'utf8'), m)).join('\n');
  const examples = {};
  for (const name of ['exceptions', 'healthy', 'incomplete']) {
    examples[name] = Object.fromEntries(['source', 'router', 'crm']
      .map(stage => [stage, readFileSync(join(root, 'examples', name, `${stage}.csv`), 'utf8')]));
  }
  const template = readFileSync(join(root, 'web', 'template.html'), 'utf8');
  for (const marker of ['/*@ENGINE@*/', '/*@EXAMPLES@*/']) {
    if (template.split(marker).length !== 2) throw new Error(`template must contain ${marker} exactly once`);
  }
  return '<!-- Generated by scripts/build-web.js from web/template.html and src/. Do not edit. -->\n' + template
    .replace('/*@ENGINE@*/', () => scriptSafe(engine))
    .replace('/*@EXAMPLES@*/', () => `const EXAMPLES = ${scriptSafe(JSON.stringify(examples))};`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const html = build();
  if (process.argv.includes('--check')) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (current !== html) {
      console.error('docs/index.html is stale: run node scripts/build-web.js');
      process.exit(1);
    }
    console.log('docs/index.html is current');
  } else {
    mkdirSync(dirname(OUT), { recursive: true });
    writeFileSync(OUT, html);
    console.log(`wrote ${OUT} (${html.length} bytes)`);
  }
}
